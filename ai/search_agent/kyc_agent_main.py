def get_user_input():
	"""Get company name and location from user"""
	print("\n" + "=" * 60)
	print("🔍 BUSINESS INTELLIGENCE RESEARCH")
	print("=" * 60)

	# Get company name
	while True:
		company_name = input("📝 Enter company name: ").strip()
		if company_name.lower() in ['quit', 'exit', 'q']:
			return None, None
		if company_name:
			break
		print("❌ Please enter a valid company name.")

